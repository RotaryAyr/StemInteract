#!/usr/bin/env python3
"""Rebuild the per-paper catalogue after adding/removing official MI PDFs.

Only real PDF files are listed. Absence means unavailable on this site, not
necessarily unpublished. Run from any directory; commit the generated JS too.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
manifest = {}
for page in sorted(ROOT.glob('*/*/*Question-Explorer.html')):
    entries = {}
    for pdf in sorted(page.parent.glob('*')):
        name = pdf.name
        if not name.lower().startswith('mi_') or pdf.suffix.lower() != '.pdf':
            continue
        if 'English-H' in str(page) and 'Critical-Reading' in name:
            continue  # RUAE has its own marking scheme.
        year = re.search(r'(\d{4})\.[pP][dD][fF]$', name)
        if not year:
            continue
        with pdf.open('rb') as stream:
            if stream.read(5) != b'%PDF-':
                raise ValueError(f'Not a PDF: {pdf}')
        paper = re.search(r'Paper-(\d)', name)
        key = year[1] + (':' + paper[1] if paper else '')
        if key in entries:
            raise ValueError(f'Duplicate marking instructions: {pdf}')
        entries[key] = name
    manifest[page.parent.relative_to(ROOT).as_posix()] = entries
output = '// Generated by scripts/build-marking-availability.py; do not infer availability from the year.\n'
output += 'window.StemMarkingAvailability = ' + json.dumps(manifest, indent=2) + ';\n'
(ROOT / 'assets/js/marking-availability.js').write_text(output)
print(f'Catalogued {sum(map(len, manifest.values()))} marking PDFs across {len(manifest)} explorers.')
