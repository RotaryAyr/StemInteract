#!/usr/bin/env python3
"""Catalogue the matching exam MI PDFs; regenerated automatically at deployment."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def scheme_pattern(page):
    name = page.name.removesuffix('-Question-Explorer.html')
    level, subject = next((code, name[len(prefix):]) for prefix, code in
                          [('Advanced-Higher-', 'NAH'), ('Higher-', 'NH'), ('N5-', 'N5')]
                          if name.startswith(prefix))
    if subject == 'English-RUAE':
        return re.compile(r'mi_NH_English_Reading-for-(?:RUAE|Understanding-Analysis-and-Evaluation)_(\d{4})\.pdf', re.I)
    separate = subject == 'Mathematics' or (level == 'NH' and subject in ['Biology', 'Human-Biology', 'Chemistry', 'Physics'])
    middle = r'Paper-(\d+)(?:-[A-Za-z-]+)?' if separate else 'mi'
    return re.compile(r'mi_' + level + '_' + re.escape(subject) + '_' + middle + r'_(\d{4})\.pdf', re.I)


def catalogue(root):
    manifest = {}
    for page in sorted(root.glob('*/*/*Question-Explorer.html')):
        entries = {}
        pattern = scheme_pattern(page)
        for pdf in sorted(page.parent.iterdir()):
            match = pattern.fullmatch(pdf.name)
            if not match or not pdf.is_file():
                continue
            with pdf.open('rb') as stream:
                if stream.read(5) != b'%PDF-':
                    print(f'Skipping unreadable PDF: {pdf}')
                    continue
            groups = match.groups()
            key = groups[-1] + (':' + groups[0] if len(groups) == 2 else '')
            if key in entries:
                raise ValueError(f'Duplicate marking instructions for {key}: {pdf}')
            entries[key] = pdf.name
        manifest[page.parent.relative_to(root).as_posix()] = entries
    return manifest


if __name__ == '__main__':
    manifest = catalogue(ROOT)
    output = '// Generated by scripts/build-marking-availability.py; do not infer availability from the year.\n'
    output += 'window.StemMarkingAvailability = ' + json.dumps(manifest, indent=2) + ';\n'
    (ROOT / 'assets/js/marking-availability.js').write_text(output)
    print(f'Catalogued {sum(map(len, manifest.values()))} marking PDFs across {len(manifest)} explorers.')
